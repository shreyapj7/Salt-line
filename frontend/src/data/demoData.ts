/**
 * Generates an illustrative inverse-distance grid over the Udupi pilot corridor.
 * Values are DEMONSTRATION ONLY and visibly flagged in the map & layer panel.
 */
export function makeDemoGrid(
  field: (loc: MonitoringLocation) => number | undefined,
  locations: MonitoringLocation[] = LOCATIONS,
  { provisional = true, scale = 1, offset = 0 }: { provisional?: boolean; scale?: number; offset?: number } = {},
): GridCell[] {
  const cells: GridCell[] = [];
  let idx = 0;
  for (let lat = 13.02; lat <= 13.4; lat += 0.035) {
    for (let lng = 74.68; lng <= 74.84; lng += 0.035) {
      let weighted = 0;
      let wsum = 0;
      for (const loc of locations) {
        const v = field(loc);
        if (v === undefined) continue;
        const d = Math.hypot(loc.lat - (lat + 0.0175), loc.lng - (lng + 0.0175));
        const w = 1 / Math.max(d * d, 0.0004);
        weighted += v * w;
        wsum += w;
      }
      if (wsum === 0) continue;
      const value = (weighted / wsum) * scale + offset;
      cells.push({ id: `cell-${idx++}`, lat, lng, sizeDeg: 0.035, value, provisional });
    }
  }
  return cells;
}

